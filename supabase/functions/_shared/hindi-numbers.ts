export function numberToHindiWords(value: number): string {
  if (!Number.isInteger(value) || value < 0) {
    throw new RangeError('Hindi number words require a non-negative integer')
  }
  if (value < 100) return HINDI_NUMBERS[value]
  for (const [scale, label] of [
    [10000000, 'करोड़'],
    [100000, 'लाख'],
    [1000, 'हज़ार'],
    [100, 'सौ'],
  ] as const) {
    if (value >= scale) {
      const remainder = value % scale
      return `${numberToHindiWords(Math.floor(value / scale))} ${label}${remainder ? ` ${numberToHindiWords(remainder)}` : ''}`
    }
  }
  throw new RangeError('Unable to convert Hindi number')
}
